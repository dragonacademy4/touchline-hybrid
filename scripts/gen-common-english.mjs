// Generates src/lib/commonEnglish.ts from SCOWL's most common English words
// (wordlist-english: "english" and "british" lists, sizes 10 and 20; SCOWL keeps
// proper names in separate lists, so these are ordinary words). Used to tell
// "Great job" from "Mason was great" at the start of a sentence.
import { readFileSync, writeFileSync } from 'node:fs';
const dir = 'node_modules/wordlist-english';
const load = (f) => JSON.parse(readFileSync(`${dir}/${f}`, 'utf8'));
const all = ['english-words-10.json', 'english-words-20.json', 'british-words-10.json', 'british-words-20.json'].flatMap(load);
const words = [...new Set(all.map((w) => w.toLowerCase()).filter((w) => /^[a-z']+$/.test(w)))].sort();
const notice = readFileSync(`${dir}/Copyright`, 'utf8').split('\n\n').slice(0, 3).join('\n\n');
writeFileSync(
  'src/lib/commonEnglish.ts',
  `// Generated by scripts/gen-common-english.mjs from SCOWL (wordlist-english). Do not edit.\n` +
    notice.split('\n').map((l) => `// ${l}`.trimEnd()).join('\n') +
    `\nexport const COMMON_ENGLISH: ReadonlySet<string> = new Set(${JSON.stringify(words.join(' '))}.split(' '));\n`,
);
console.log(words.length, 'words');
