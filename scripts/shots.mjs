// Quick visual pass: walks the main screens and saves screenshots.
import { chromium } from '@playwright/test';
const width = Number(process.argv[2] ?? 375);
const out = process.argv[3] ?? '../qa/dev';
const theme = process.argv[4] ?? 'light';
const b = await chromium.launch({ channel: 'chrome' });
const ctx = await b.newContext({ viewport: { width, height: width < 500 ? 812 : 900 }, deviceScaleFactor: 1, colorScheme: theme });
const p = await ctx.newPage();
const errors = [];
p.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.text()); });
p.on('pageerror', (e) => errors.push(String(e)));
const shot = async (n) => p.screenshot({ path: `${out}/${width}-${theme}-${n}.png`, fullPage: !/sheet/.test(n) });
await p.goto('http://localhost:4173/');
await p.waitForTimeout(800);
await shot('01-welcome');
await p.getByRole('button', { name: 'Try the demo squad' }).click();
await p.waitForTimeout(600);
await shot('02-today');
await p.getByRole('button', { name: /Start today's session/ }).click();
await p.waitForTimeout(400);
await shot('03-start-sheet');
await p.getByRole('button', { name: 'Passing and receiving' }).click();
await p.getByRole('button', { name: 'Start capturing' }).click();
await p.waitForTimeout(500);
await shot('04-capture');
await p.getByRole('button', { name: /^Ollie/ }).click();
await p.waitForTimeout(400);
await p.getByRole('button', { name: 'Brave' }).click();
await p.getByRole('button', { name: 'Weak foot' }).click();
await p.getByRole('textbox', { name: 'Anything else?' }).fill('Ollie scored with his left foot and helped Seren up after she fell');
await shot('05-note-sheet');
await p.getByRole('button', { name: 'Done' }).click();
await p.waitForTimeout(300);
await shot('06-capture-noted');
await p.goto('http://localhost:4173/#/squad'); await p.waitForTimeout(400); await shot('07-squad');
await p.goto('http://localhost:4173/#/player/demo-p4'); await p.waitForTimeout(400); await shot('08-player');
await p.goto('http://localhost:4173/#/updates'); await p.waitForTimeout(400); await shot('09-updates');
await p.goto('http://localhost:4173/#/settings'); await p.waitForTimeout(400); await shot('10-settings');
await p.goto('http://localhost:4173/#/session/demo-s3/review'); await p.waitForTimeout(400); await shot('11-review');
await p.goto('http://localhost:4173/#/session/demo-s3/card/demo-p4'); await p.waitForTimeout(600); await shot('12-card');
await p.goto('http://localhost:4173/#/privacy'); await p.waitForTimeout(300); await shot('13-privacy');
console.log('console errors/warnings:', JSON.stringify(errors, null, 1));
await b.close();
